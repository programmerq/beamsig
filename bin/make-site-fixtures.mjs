// Generate docs/vendor/fixture-data.js from the committed fixtures, so the
// landing page's "verify it yourself" widget has real signatures to check
// without fetching anything.
//
//   node bin/make-site-fixtures.mjs        (usually via bin/sync-site-libs.sh)
//
// Two reasons this is inlined rather than fetched:
//   * GitHub Pages serving /docs does not publish the repo-root fixtures/.
//   * fetch() is blocked on file://, and the page is meant to work there too.
//
// Only the jeff.beams.sh fixtures are used. They are already public in the
// upstream repo, so publishing them exposes nothing new — unlike a live beam's
// signatures, which embed that beam's owner email and login IP.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..");
const fx = (p) => readFileSync(join(repo, "fixtures", p), "utf8");

// claimedTime values must fall inside each signature's embedded certificate
// window (1791210987 .. 1791214647 for both of these), or verification fails
// closed on the time check.
const data = {
  // A real beam signature over fixtures/msg.txt, SSHSIG namespace "git".
  signed: {
    signature: fx("sig-from-cert.sig"),
    message: fx("msg.txt"),
    namespace: "git",
    claimedTime: 1791212000,
  },
  // The same payload signed with a BARE KEY: no certificate is embedded, so
  // there is no beam identity to establish at all. The instructive negative.
  bareKey: {
    signature: fx("sig-from-key.sig"),
    message: fx("msg.txt"),
    namespace: "git",
    claimedTime: 1791212000,
  },
  // Signed at 15:11:29 but attested as 14:37:27 — 34 minutes earlier — by
  // embedding a certificate the beam still held. This VERIFIES, which is
  // exactly the point. claimedTime is the value REPORT.md §4(c) documents.
  backdated: {
    signature: fx("backdated.sig"),
    message: fx("backdated.txt"),
    namespace: "beamsig.artifact.v1",
    claimedTime: 1791211047,
  },
};

mkdirSync(join(repo, "docs", "vendor"), { recursive: true });
writeFileSync(
  join(repo, "docs", "vendor", "fixture-data.js"),
  "// GENERATED COPY — do not edit this file.\n" +
    "// Source of truth: fixtures/ (via bin/make-site-fixtures.mjs)\n" +
    "// Re-sync with:    bin/sync-site-libs.sh\n" +
    `globalThis.BEAMSIG_FIXTURES = ${JSON.stringify(data, null, 2)};\n`
);

console.log("  docs/vendor/fixture-data.js");

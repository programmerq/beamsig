#!/usr/bin/env bash
# Copy the extension's verification/avatar libraries into docs/vendor/ so the
# landing page can load them.
#
#   bin/sync-site-libs.sh
#
# Why a copy exists at all: GitHub Pages serving /docs publishes ONLY the
# contents of docs/, so docs/index.html cannot reference ../extension/src/lib/.
# extension/src/lib/ stays the single source of truth; everything in
# docs/vendor/ is generated. extension/test/site-sync.mjs fails if the copies
# drift, so this is enforced rather than hoped for.
set -euo pipefail
LAB="${BEAMSIG_HOME:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
cd "$LAB"

SRC="extension/src/lib"
DST="docs/vendor"
# Load order matters: each file destructures its dependencies at execution
# time, so an out-of-order <script> tag throws immediately.
LIBS=(wire.js sshcert.js sshsig.js sshcrypto.js ca.js verify.js avatar.js)

mkdir -p "$DST"

for f in "${LIBS[@]}"; do
  if [ ! -f "$SRC/$f" ]; then
    echo "missing $SRC/$f — are you on a branch that includes the extension?" >&2
    exit 1
  fi
  {
    printf '// GENERATED COPY — do not edit this file.\n'
    printf '// Source of truth: %s\n' "$SRC/$f"
    printf '// Re-sync with:    bin/sync-site-libs.sh\n'
    printf '// %s\n' "--- BEGIN VERBATIM COPY ---"
    cat "$SRC/$f"
  } > "$DST/$f"
  echo "  $DST/$f"
done

echo "== generating inlined fixture data =="
# The fixtures live at the repo root, which Pages also does not publish, so the
# bytes are inlined into a JS file instead of fetched.
node bin/make-site-fixtures.mjs

echo
echo "Done. Verify with: node extension/test/site-sync.mjs"

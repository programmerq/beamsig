// Generate test/preview-data.js from the committed fixtures, so preview.html
// has a real beam signature to render without fetching anything (file:// fetch
// is blocked in Chrome) and without a second copy of the fixture to drift.
//
//   node extension/test/make-preview-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const fx = (p) => readFileSync(join(repo, "fixtures", p), "utf8");

const data = {
  // A real beam signature over fixtures/msg.txt, namespace "git".
  signature: fx("sig-from-cert.sig"),
  message: fx("msg.txt"),
  // A time inside the embedded certificate's window.
  claimedTime: 1791212000,
  // Signed with a bare key: no certificate, so no identity at all.
  bareKeySignature: fx("sig-from-key.sig"),
};

writeFileSync(
  join(here, "preview-data.js"),
  "// GENERATED by make-preview-data.mjs — do not edit.\n" +
    `globalThis.BEAMSIG_PREVIEW = ${JSON.stringify(data, null, 2)};\n`
);

console.log("wrote extension/test/preview-data.js");
